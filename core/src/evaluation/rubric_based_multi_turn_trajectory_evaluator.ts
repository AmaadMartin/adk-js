/**
 * Evaluates the quality of an agent's behavior across an entire multi-turn
 * conversation using rubrics and an LLM judge.
 *
 * The full dialogue history (user turns, agent turns, and tool interactions) is
 * accumulated and a single LLM-based evaluation is performed on the last turn
 * using the complete conversation context. The first N-1 turns are marked
 * NOT_EVALUATED and the final turn carries the aggregate score.
 */
export class RubricBasedMultiTurnTrajectoryEvaluator extends RubricBasedEvaluator {
  static readonly RUBRIC_TYPE = 'TRAJECTORY_QUALITY';

  protected formattedDialogue = '';
  protected formattedInstructions = '';
  protected formattedTools = '';

  constructor(evalMetric: EvalMetric) {
    super(evalMetric, RubricBasedMultiTurnTrajectoryEvaluator.RUBRIC_TYPE);
  }

  protected assembleDialogueHistory(actualInvocations: Invocation[]): void {
    const dialogueLines: string[] = [];
    for (let turnIndex = 0; turnIndex < actualInvocations.length; turnIndex++) {
      const invocation = actualInvocations[turnIndex];
      const turn = turnIndex + 1;

      // USER TURN
      if (invocation.userContent && invocation.userContent.parts) {
        const textParts = invocation.userContent.parts
          .map((part) => part.text)
          .filter((text): text is string => !!text);
        if (textParts.length) {
          dialogueLines.push(`USER TURN ${turn}: ${textParts.join(' ')}`);
        }
      }

      // INTERMEDIATE TOOL EVENTS
      const intermediate = invocation.intermediateData;
      if (intermediate && 'invocationEvents' in intermediate) {
        for (const event of intermediate.invocationEvents) {
          const role =
            event.author && event.author.toLowerCase() === 'user'
              ? 'USER'
              : `AGENT (${event.author})`;
          if (!event.content || !event.content.parts) {
            continue;
          }
          const textParts = event.content.parts
            .map((part) => part.text)
            .filter((text): text is string => !!text);
          if (textParts.length) {
            dialogueLines.push(`${role} TURN ${turn}: ${textParts.join(' ')}`);
          }
          for (const part of event.content.parts) {
            if (part.functionCall) {
              const args = part.functionCall.args
                ? JSON.stringify(part.functionCall.args)
                : '{}';
              dialogueLines.push(
                `${role} TURN ${turn} (tool call): ${part.functionCall.name}(${args})`,
              );
            }
            if (part.functionResponse) {
              const response = part.functionResponse.response
                ? JSON.stringify(part.functionResponse.response)
                : '{}';
              dialogueLines.push(
                `${role} TURN ${turn} (tool output): ${part.functionResponse.name} -> ${response}`,
              );
            }
          }
        }
      }

      // FINAL AGENT TURN
      if (invocation.finalResponse && invocation.finalResponse.parts) {
        let agentName = 'agent';
        if (
          intermediate &&
          'invocationEvents' in intermediate &&
          intermediate.invocationEvents.length > 0
        ) {
          agentName = intermediate.invocationEvents[0].author;
        }
        const role = `AGENT (${agentName})`;
        const textParts = invocation.finalResponse.parts
          .map((part) => part.text)
          .filter((text): text is string => !!text);
        if (textParts.length) {
          dialogueLines.push(`${role} TURN ${turn}: ${textParts.join(' ')}`);
        }
      }
    }

    this.formattedDialogue = dialogueLines.join('\n');

    // Collect instructions and tools locally from each invocation.
    const instructionsParts: string[] = [];
    const toolsParts: string[] = [];
    for (const invocation of actualInvocations) {
      const appDetails = invocation.appDetails;
      if (!appDetails) {
        continue;
      }
      for (const [agentId, details] of Object.entries(
        appDetails.agentDetails,
      )) {
        instructionsParts.push(
          `Agent ${agentId} Instructions:\n${details.instructions}`,
        );
        toolsParts.push(`Agent: ${agentId}`);
        for (const tool of details.toolDeclarations) {
          for (const func of (tool as Tool).functionDeclarations ?? []) {
            toolsParts.push(`- ${func.name}: ${func.description}`);
          }
        }
      }
    }

    // dict.fromkeys(...) dedups while preserving insertion order.
    this.formattedInstructions = [...new Set(instructionsParts)].join('\n\n');
    this.formattedTools = [...new Set(toolsParts)].join('\n');
  }

  override async evaluateInvocations(
    actualInvocations: Invocation[],
    expectedInvocations?: Invocation[],
    conversationScenario?: ConversationScenario,
  ): Promise<EvaluationResult> {
    logger.debug(
      `Local evaluator start (invocations: ${actualInvocations.length})`,
    );
    validateInvocationLengths(actualInvocations, expectedInvocations);
    if (actualInvocations.length === 0) {
      return {
        overallEvalStatus: EvalStatus.NOT_EVALUATED,
        perInvocationResults: [],
      };
    }
    this.assembleDialogueHistory(actualInvocations);

    const expected: Array<Invocation | undefined> =
      expectedInvocations ?? actualInvocations.map(() => undefined);

    // Mark the first N-1 turns as NOT_EVALUATED.
    const perInvocationResults: PerInvocationResult[] = [];
    for (let i = 0; i < actualInvocations.length - 1; i++) {
      perInvocationResults.push({
        actualInvocation: actualInvocations[i],
        expectedInvocation: expected[i],
        score: undefined,
        evalStatus: EvalStatus.NOT_EVALUATED,
      });
    }

    // Conversation-level evaluation: run the judge once on the last turn with
    // the full dialogue context.
    const lastIndex = actualInvocations.length - 1;
    const lastExpectedInvocation = expected[lastIndex];
    const lastExpected = lastExpectedInvocation
      ? [lastExpectedInvocation]
      : undefined;
    const lastTurnResult = await super.evaluateInvocations(
      [actualInvocations[lastIndex]],
      lastExpected,
      conversationScenario,
    );

    if (lastTurnResult.perInvocationResults.length > 0) {
      perInvocationResults.push(...lastTurnResult.perInvocationResults);
    } else {
      perInvocationResults.push({
        actualInvocation: actualInvocations[lastIndex],
        expectedInvocation: expected[lastIndex],
        score: lastTurnResult.overallScore,
        evalStatus: lastTurnResult.overallEvalStatus,
        rubricScores: lastTurnResult.overallRubricScores,
      });
    }

    return {
      overallScore: lastTurnResult.overallScore,
      overallEvalStatus: lastTurnResult.overallEvalStatus,
      perInvocationResults,
      overallRubricScores: lastTurnResult.overallRubricScores,
    };
  }

  override formatAutoRaterPrompt(
    actualInvocation: Invocation,
    _expectedInvocation?: Invocation,
  ): string {
    this.createEffectiveRubricsList(actualInvocation.rubrics);
    logger.debug(
      `format_auto_rater_prompt called (effective rubrics: ${
        this.getEffectiveRubricsList().length
      })`,
    );

    const rubricsList = this.getEffectiveRubricsList().map((rubric) => {
      const entry: {id: string; property?: string; type?: string} = {
        id: rubric.rubricId,
        property: rubric.rubricContent.textProperty,
      };
      if (rubric.type) {
        entry.type = rubric.type;
      }
      return entry;
    });
    const formattedRubrics = JSON.stringify(rubricsList, null, 2);

    const prompt = multiTurnTrajectoryPrompt({
      userAgentDialogue: this.formattedDialogue,
      properties: formattedRubrics,
      agentInstructions: this.formattedInstructions,
      agentToolDefinitions: this.formattedTools,
    });
    logger.debug(`Generated rubric validator prompt:\n${prompt}`);
    return prompt;
  }
}
