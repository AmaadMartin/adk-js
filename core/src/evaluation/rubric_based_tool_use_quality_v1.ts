/**
 * Grades how an agent used its tools against written rubrics.
 *
 * Take a weather agent with two tools: a geocoding tool that turns a place
 * name into coordinates, and a forecast tool that reads coordinates. There is
 * no single golden answer, but the tool usage still has properties worth
 * pinning:
 *
 * - A call is made to the geocoding tool.
 * - The call to the forecast tool happens after the geocoding call.
 * - The input to the forecast tool comes from the geocoding output.
 *
 * Each property is one rubric. A judge model answers `yes` or `no` per rubric;
 * a `yes` scores 1.0 and a `no` scores 0.0, and the invocation scores the mean
 * of its rubrics. Repeated judge samples are settled by majority vote, and the
 * eval case scores the mean over its invocations.
 */
@experimental
export class RubricBasedToolUseV1Evaluator extends RubricBasedEvaluator {
  /** The type of the invocation rubrics this metric grades. */
  static readonly RUBRIC_TYPE = 'TOOL_USE_QUALITY';

  constructor(evalMetric: EvalMetric, judgeModel?: BaseLlm) {
    super({
      evalMetric,
      rubricType: RubricBasedToolUseV1Evaluator.RUBRIC_TYPE,
      judgeModel,
    });
  }

  /**
   * Returns the prompt that grades one invocation.
   *
   * adk-python takes the expected invocation here and ignores it, so this
   * override omits the parameter.
   *
   * @throws {InputValidationError} When two rubrics share an id, or no rubric
   *   applies to the invocation.
   */
  override formatAutoRaterPrompt(actual: Invocation): string {
    this.createEffectiveRubricsList(actual.rubrics);
    const appDetails = actual.appDetails;

    return formatPromptTemplate(RUBRIC_BASED_TOOL_USE_QUALITY_V1_PROMPT, {
      tool_declarations:
        appDetails === undefined
          ? NO_TOOLS_TEXT
          : getToolDeclarationsAsJsonStr(appDetails),
      user_input: getTextFromContent(actual.userContent),
      tool_usage: getToolCallsAndResponsesAsJsonStr(actual.intermediateData),
      rubrics: this.getEffectiveRubricsList()
        .map(
          (rubric) =>
            `*  [id: ${rubric.rubricId}] ${rubric.rubricContent.textProperty}`,
        )
        .join('\n'),
    });
  }
}
