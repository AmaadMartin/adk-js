import {Content, FunctionCall, FunctionResponse, Part} from '@google/genai';
import {z} from 'zod';

import {AppDetailsSchema} from './app_details.js';
import {ConversationScenarioSchema} from './conversation_scenarios.js';
import {RubricSchema} from './eval_rubrics.js';

// genai payloads are embedded via `z.custom<T>()`: this yields the correct
// inferred TS type and accepts the value at runtime without re-defining genai's
// own schema (parity with adk-python, where genai models validate themselves).

/**
 * Container for intermediate data an agent generates while producing a final
 * answer.
 */
export const IntermediateDataSchema = z
  .object({
    /** Tool use trajectory in chronological order. */
    toolUses: z.array(z.custom<FunctionCall>()).default(() => []),
    /** Tool response trajectory in chronological order. */
    toolResponses: z.array(z.custom<FunctionResponse>()).default(() => []),
    /**
     * Intermediate responses generated by sub-agents to convey progress or
     * status, distinct from the final response. Each entry is a tuple of the
     * author (usually the sub-agent name) and the parts that comprise the
     * response.
     */
    intermediateResponses: z
      .array(z.tuple([z.string(), z.array(z.custom<Part>())]))
      .default(() => []),
  })
  .strict();

/**
 * Container for intermediate data an agent generates while producing a final
 * answer.
 */
export type IntermediateData = z.infer<typeof IntermediateDataSchema>;

/**
 * An immutable record representing a specific point in the agent's invocation.
 *
 * A simple projection of the full `Event` datamodel intended for the eval
 * system.
 */
export const InvocationEventSchema = z
  .object({
    /** The name of the agent that authored/owned this event. */
    author: z.string(),
    /** The content of the event. */
    content: z.custom<Content>().optional(),
  })
  .strict();

/**
 * An immutable record representing a specific point in the agent's invocation.
 */
export type InvocationEvent = z.infer<typeof InvocationEventSchema>;

/**
 * A container for events that occur during the course of an invocation.
 */
export const InvocationEventsSchema = z
  .object({
    /** A list of invocation events. */
    invocationEvents: z.array(InvocationEventSchema).default(() => []),
  })
  .strict();

/**
 * A container for events that occur during the course of an invocation.
 */
export type InvocationEvents = z.infer<typeof InvocationEventsSchema>;

/**
 * The two supported shapes of intermediate data: a flat {@link IntermediateData}
 * or an event stream ({@link InvocationEvents}).
 */
export const IntermediateDataTypeSchema = z.union([
  IntermediateDataSchema,
  InvocationEventsSchema,
]);

/**
 * The two supported shapes of intermediate data.
 */
export type IntermediateDataType = z.infer<typeof IntermediateDataTypeSchema>;

/**
 * Represents a single invocation.
 */
export const InvocationSchema = z
  .object({
    /** Unique identifier for the invocation. */
    invocationId: z.string().default(''),
    /** Content provided by the user in this invocation. */
    userContent: z.custom<Content>(),
    /** Final response from the agent. */
    finalResponse: z.custom<Content>().optional(),
    /**
     * Intermediate steps generated as part of agent execution. For a
     * multi-agent system this also captures the route the agent took.
     */
    intermediateData: IntermediateDataTypeSchema.optional(),
    /** Timestamp for this invocation, primarily intended for debugging. */
    creationTimestamp: z.number().default(0),
    /** Rubrics applicable only to this invocation. */
    rubrics: z.array(RubricSchema).optional(),
    /** Details about the App that was used for this invocation. */
    appDetails: AppDetailsSchema.optional(),
  })
  .strict();

/**
 * Represents a single invocation.
 */
export type Invocation = z.infer<typeof InvocationSchema>;

/**
 * The state of a session.
 */
export type SessionState = Record<string, unknown>;

/**
 * Values that help initialize a Session.
 *
 * Preserves unknown ("extra") properties round-trip (parity with adk-python's
 * `extra="allow"`).
 */
export const SessionInputSchema = z
  .object({
    /** The name of the app. */
    appName: z.string(),
    /** The user id. */
    userId: z.string(),
    /** The state of the session. */
    state: z.record(z.string(), z.unknown()).default(() => ({})),
  })
  .loose();

/**
 * Values that help initialize a Session.
 */
export type SessionInput = z.infer<typeof SessionInputSchema>;

/**
 * A conversation where the user's queries for each invocation are already
 * specified.
 */
export type StaticConversation = Invocation[];

/**
 * An eval case.
 *
 * Preserves unknown ("extra") properties round-trip (parity with adk-python's
 * `extra="allow"`).
 */
export const EvalCaseSchema = z
  .object({
    /** Unique identifier for the evaluation case. */
    evalId: z.string(),
    /**
     * A static conversation between the user and the agent. Specify either
     * `conversation` or `conversationScenario`, but not both.
     */
    conversation: z.array(InvocationSchema).optional(),
    /**
     * A conversation scenario that should be used by a user simulator. Specify
     * either `conversation` or `conversationScenario`, but not both.
     */
    conversationScenario: ConversationScenarioSchema.optional(),
    /** Session input passed to the agent during eval. */
    sessionInput: SessionInputSchema.optional(),
    /** The time at which this eval case was created. */
    creationTimestamp: z.number().default(0),
    /** Rubrics applicable to all invocations in this eval case. */
    rubrics: z.array(RubricSchema).optional(),
    /** The expected final session state at the end of the conversation. */
    finalSessionState: z.record(z.string(), z.unknown()).default(() => ({})),
  })
  .loose()
  .refine(
    (data) =>
      (data.conversation === undefined) !==
      (data.conversationScenario === undefined),
    {
      message:
        'Exactly one of conversation and conversation_scenario must be' +
        ' provided in an EvalCase.',
    },
  );

/**
 * An eval case.
 */
export type EvalCase = z.infer<typeof EvalCaseSchema>;

/**
 * A tuple pairing a function call with its corresponding function response, if
 * one is available.
 */
export type ToolCallAndResponse = [FunctionCall, FunctionResponse | undefined];

function isIntermediateData(data: object): data is IntermediateData {
  return 'toolUses' in data;
}

function isInvocationEvents(data: object): data is InvocationEvents {
  return 'invocationEvents' in data;
}

function collectFromEvents<T>(
  events: InvocationEvents,
  select: (part: Part) => T | undefined,
): T[] {
  const collected: T[] = [];
  for (const event of events.invocationEvents) {
    for (const part of event.content?.parts ?? []) {
      const value = select(part);
      if (value) {
        collected.push(value);
      }
    }
  }
  return collected;
}

/**
 * Retrieves all tool calls from intermediate data.
 *
 * @returns An empty array when `intermediateData` is undefined.
 * @throws {Error} If `intermediateData` is of an unsupported shape.
 */
export function getAllToolCalls(
  intermediateData?: IntermediateDataType,
): FunctionCall[] {
  if (!intermediateData) {
    return [];
  }
  if (typeof intermediateData === 'object') {
    if (isIntermediateData(intermediateData)) {
      return intermediateData.toolUses;
    }
    if (isInvocationEvents(intermediateData)) {
      return collectFromEvents(intermediateData, (part) => part.functionCall);
    }
  }
  throw new Error(
    `Unsupported type for intermediate_data \`${intermediateData}\``,
  );
}

/**
 * Retrieves all tool responses from intermediate data.
 *
 * @returns An empty array when `intermediateData` is undefined.
 * @throws {Error} If `intermediateData` is of an unsupported shape.
 */
export function getAllToolResponses(
  intermediateData?: IntermediateDataType,
): FunctionResponse[] {
  if (!intermediateData) {
    return [];
  }
  if (typeof intermediateData === 'object') {
    if (isIntermediateData(intermediateData)) {
      return intermediateData.toolResponses;
    }
    if (isInvocationEvents(intermediateData)) {
      return collectFromEvents(
        intermediateData,
        (part) => part.functionResponse,
      );
    }
  }
  throw new Error(
    `Unsupported type for intermediate_data \`${intermediateData}\``,
  );
}

/**
 * Returns tool calls paired with their corresponding responses, matched by
 * call id. Responses without a matching call are dropped; calls without a
 * matching response are paired with `undefined`.
 */
export function getAllToolCallsWithResponses(
  intermediateData?: IntermediateDataType,
): ToolCallAndResponse[] {
  const responsesByCallId = new Map<string | undefined, FunctionResponse>();
  for (const response of getAllToolResponses(intermediateData)) {
    responsesByCallId.set(response.id, response);
  }
  return getAllToolCalls(intermediateData).map(
    (call): ToolCallAndResponse => [call, responsesByCallId.get(call.id)],
  );
}
