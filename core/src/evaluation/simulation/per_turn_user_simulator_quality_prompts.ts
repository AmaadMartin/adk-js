/** Matches a `{{ ... }}` block, capturing what is inside it. */
const INTERPOLATION = /\{\{\s*([^{}]*?)\s*\}\}/g;

/** Matches a dotted path of identifiers, and nothing more complex. */
const DOTTED_PATH = /^[A-Za-z_$][\w$]*(\.[A-Za-z_$][\w$]*)*$/;

/** Reports whether a value can carry properties. */
function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null;
}

/**
 * Substitutes `{{ dotted.path }}` references against `variables`.
 *
 * Only a plain dotted path over an own property is substituted. Anything else,
 * a call or a prototype walk included, renders empty, and a substituted value
 * is never rescanned. adk-python compiles a template with Jinja's
 * `SandboxedEnvironment`; a persona field may come from a data file and the
 * agent under test writes part of the conversation history, so nothing is
 * compiled here.
 */
function interpolateVariables(
  templateStr: string,
  variables: Record<string, unknown>,
): string {
  return templateStr.replace(INTERPOLATION, (_match, expression: string) => {
    if (!DOTTED_PATH.test(expression)) {
      return '';
    }
    let current: unknown = variables;
    for (const segment of expression.split('.')) {
      if (
        !isRecord(current) ||
        !Object.prototype.hasOwnProperty.call(current, segment)
      ) {
        return '';
      }
      current = current[segment];
    }
    return String(current);
  });
}

/**
 * Renders one persona field, which may itself name a variable.
 *
 * This is adk-python's `render_string_filter`: the field is rendered against
 * the variables of the enclosing prompt.
 */
function renderPersonaField(
  value: string,
  variables: Record<string, unknown>,
): string {
  return value ? interpolateVariables(value, variables) : '';
}

/** Renders one behavior's criteria entry. */
function renderBehavior(
  behavior: UserBehavior,
  variables: Record<string, unknown>,
): string {
  return interpolateVariables(PERSONA_BEHAVIOR_TEMPLATE, {
    name: renderPersonaField(behavior.name, variables),
    description: renderPersonaField(behavior.description, variables),
    violation_rubrics_str: renderPersonaField(
      behavior.violationRubrics.map((rubric) => `  * ${rubric}`).join('\n'),
      variables,
    ),
  });
}

/**
 * Renders the prompt that asks a judge model to grade one simulated user turn.
 *
 * @param params.conversationPlan The plan the simulated user was to follow.
 * @param params.conversationHistory The conversation before this turn.
 * @param params.generatedUserResponse The simulated user turn under judgement.
 * @param params.stopSignal The text that marks the conversation complete.
 * @param params.userPersona The persona the simulated user adopted.
 * @returns The rendered prompt.
 */
export function getPerTurnUserSimulatorQualityPrompt(params: {
  conversationPlan: string;
  conversationHistory: string;
  generatedUserResponse: string;
  stopSignal: string;
  userPersona?: UserPersona;
}): string {
  const variables: Record<string, unknown> = {
    conversation_plan: params.conversationPlan,
    conversation_history: params.conversationHistory,
    generated_user_response: params.generatedUserResponse,
    stop_signal: params.stopSignal,
  };
  const persona = params.userPersona;
  if (persona === undefined) {
    return interpolateVariables(DEFAULT_JUDGE_TEMPLATE, variables);
  }

  variables['persona'] = persona;
  return (
    interpolateVariables(PERSONA_JUDGE_TEMPLATE_HEAD, variables) +
    persona.behaviors
      .map((behavior) => renderBehavior(behavior, variables))
      .join('') +
    interpolateVariables(PERSONA_JUDGE_TEMPLATE_TAIL, variables)
  );
}
