/**
 * Returns the judge prompt template for a scenario, which depends only on
 * whether the scenario names a persona.
 *
 * adk-python's `_get_latest_turn_user_simulator_quality_prompt_template`.
 */
export function getLatestTurnUserSimulatorQualityPromptTemplate(
  userPersona?: UserPersona,
): string {
  return userPersona === undefined
    ? LATEST_TURN_USER_SIMULATOR_EVALUATOR_PROMPT_TEMPLATE
    : LATEST_TURN_USER_SIMULATOR_WITH_PERSONA_EVALUATOR_PROMPT_TEMPLATE;
}

/** A value a template placeholder resolves to, or a loop iterates over. */
type TemplateValue = string | TemplateScope | TemplateScope[];

/** The variables one render pass reads. */
interface TemplateScope {
  readonly [name: string]: TemplateValue;
}

/**
 * Matches a `{% for x in a.b %} … {% endfor %}` block, or a `{{ … }}`
 * placeholder. One alternation, so a single left-to-right pass expands both
 * and never revisits what it substituted.
 */
const TEMPLATE_PATTERN =
  /\{%\s*for\s+(\w+)\s+in\s+([\w.]+)\s*%\}([\s\S]*?)\{%\s*endfor\s*%\}|\{\{([^{}]*)\}\}/g;

/** Matches a `{{ … }}` placeholder alone. */
const PLACEHOLDER_PATTERN = /\{\{([^{}]*)\}\}/g;

/** The one filter the persona template applies. */
const RENDER_STRING_FILTER = 'render_string_filter';

/**
 * Matches a plain dotted path over own properties. A segment may end in `()`,
 * which reads a precomputed key such as {@link VIOLATION_RUBRICS_KEY} rather
 * than calling anything.
 */
const DOTTED_PATH_PATTERN =
  /^[A-Za-z_]\w*(?:\(\))?(?:\.[A-Za-z_]\w*(?:\(\))?)*$/;

/** The key the persona template reads the rendered violation rubrics through. */
const VIOLATION_RUBRICS_KEY = 'get_violation_rubrics_str()';

/** adk-python's `UserBehavior.get_violation_rubrics_str()`. */
function formatViolationRubrics(behavior: UserBehavior): string {
  return behavior.violationRubrics.map((rubric) => `  * ${rubric}`).join('\n');
}

/** Returns the value a dotted path names, or undefined when it names none. */
function resolvePath(
  scope: TemplateScope,
  path: string,
): TemplateValue | undefined {
  if (!DOTTED_PATH_PATTERN.test(path)) {
    return undefined;
  }

  let current: TemplateValue = scope;
  for (const segment of path.split('.')) {
    if (typeof current !== 'object' || Array.isArray(current)) {
      return undefined;
    }
    if (!Object.hasOwn(current, segment)) {
      return undefined;
    }
    current = current[segment];
  }
  return current;
}

/** Returns the text a dotted path names, or `''` when it names no text. */
function readText(scope: TemplateScope, path: string): string {
  const value = resolvePath(scope, path.trim());
  return typeof value === 'string' ? value : '';
}

/**
 * Substitutes the placeholders of a persona field, ignoring any filter it
 * names. This is the bottom of the render, so a persona field that names
 * itself substitutes once instead of recursing.
 */
function renderPersonaField(field: string, scope: TemplateScope): string {
  return field.replace(PLACEHOLDER_PATTERN, (_match, expression: string) =>
    readText(scope, expression.split('|')[0]),
  );
}

/** Substitutes one `{{ … }}` placeholder, applying the filter it names. */
function substitute(expression: string, scope: TemplateScope): string {
  const [path, filter] = expression.split('|');
  const text = readText(scope, path);
  return filter?.trim() === RENDER_STRING_FILTER
    ? renderPersonaField(text, scope)
    : text;
}

/** Repeats a loop body once per item, binding the item under `name`. */
function renderLoop(
  name: string,
  path: string,
  body: string,
  scope: TemplateScope,
): string {
  const items = resolvePath(scope, path);
  if (!Array.isArray(items)) {
    return '';
  }
  return items
    .map((item) => renderTemplate(body, {...scope, [name]: item}))
    .join('');
}

/**
 * Renders a judge prompt template.
 *
 * This is deliberately not a template engine: it substitutes a dotted path
 * over own properties and repeats one `for` block, and it compiles and
 * evaluates nothing. That matters because both inputs are untrusted — a
 * persona field is read from a data file, and the agent under test writes part
 * of the conversation history. Any other expression, a call or a prototype
 * walk included, substitutes as the empty string. A substituted value is never
 * rescanned.
 */
function renderTemplate(template: string, scope: TemplateScope): string {
  return template.replace(
    TEMPLATE_PATTERN,
    (
      _match: string,
      loopName: string | undefined,
      loopPath: string | undefined,
      loopBody: string | undefined,
      expression: string | undefined,
    ): string =>
      loopName !== undefined && loopPath !== undefined && loopBody !== undefined
        ? renderLoop(loopName, loopPath, loopBody, scope)
        : substitute(expression ?? '', scope),
  );
}

/**
 * Returns the persona as template variables, with each behavior's violation
 * rubrics already rendered under the key the template reads them through.
 */
function toPersonaScope(persona: UserPersona): TemplateScope {
  return {
    id: persona.id,
    description: persona.description,
    behaviors: persona.behaviors.map((behavior) => ({
      name: behavior.name,
      description: behavior.description,
      [VIOLATION_RUBRICS_KEY]: formatViolationRubrics(behavior),
    })),
  };
}

/**
 * Builds the prompt that asks a judge model whether one simulated user turn
 * kept to its conversation plan.
 *
 * The template variables keep adk-python's snake_case names, because a persona
 * author writes them into persona text that this renders.
 *
 * @param params.conversationPlan The plan the simulated user follows.
 * @param params.conversationHistory The conversation so far, already
 *   formatted.
 * @param params.generatedUserResponse The simulated user turn under judgement.
 * @param params.stopSignal The token that marks the conversation complete.
 * @param params.userPersona The persona the simulated user adopts. Selects the
 *   persona template when present.
 */
export function getPerTurnUserSimulatorQualityPrompt(params: {
  conversationPlan: string;
  conversationHistory: string;
  generatedUserResponse: string;
  stopSignal: string;
  userPersona?: UserPersona;
}): string {
  const scope: Record<string, TemplateValue> = {
    conversation_plan: params.conversationPlan,
    conversation_history: params.conversationHistory,
    generated_user_response: params.generatedUserResponse,
    stop_signal: params.stopSignal,
  };
  if (params.userPersona !== undefined) {
    scope['persona'] = toPersonaScope(params.userPersona);
  }
  return renderTemplate(
    getLatestTurnUserSimulatorQualityPromptTemplate(params.userPersona),
    scope,
  );
}
